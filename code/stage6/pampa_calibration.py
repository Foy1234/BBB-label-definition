#!/usr/bin/env python3
"""Cross-fitted Platt calibration analysis for frozen PAMPA-BBB predictions.

The script reads the Stage IV per-seed PAMPA predictions, averages the 20
XGBoost seeds at the parent level for Hard, Vote and Integrated targets,
computes locked raw-score metrics, and performs three 5-fold stratified
cross-fitting repeats (seeds 42, 43 and 44). Each parent's calibrated value is
generated by a Platt model fitted on the other folds.
"""
from __future__ import annotations
import argparse, hashlib, json, platform
from pathlib import Path
import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import StratifiedKFold
from sklearn.metrics import roc_auc_score, average_precision_score, brier_score_loss, log_loss
import sklearn
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

TARGETS=("H","V","I")
TARGET_NAMES={"H":"Hard","V":"Vote","I":"Integrated"}
DEFAULT_SEEDS=(42,43,44)

def sha256(path: Path)->str:
    h=hashlib.sha256()
    with path.open("rb") as f:
        for b in iter(lambda:f.read(1<<20),b""):
            h.update(b)
    return h.hexdigest()

def ece(y,p,bins=10):
    y=np.asarray(y,int); p=np.clip(np.asarray(p,float),0,1)
    ix=np.minimum((p*bins).astype(int),bins-1)
    ans=0.0
    for j in range(bins):
        m=ix==j
        if m.any():
            ans += abs(float(p[m].mean())-float(y[m].mean()))*float(m.mean())
    return float(ans)

def metrics(y,p):
    y=np.asarray(y,int); p=np.clip(np.asarray(p,float),0,1)
    return {
        "n":int(len(y)),
        "positives":int(y.sum()),
        "auroc":float(roc_auc_score(y,p)),
        "auprc":float(average_precision_score(y,p)),
        "brier":float(brier_score_loss(y,p)),
        "ece10":ece(y,p,10),
        "logloss":float(log_loss(y,np.clip(p,1e-8,1-1e-8),labels=[0,1])),
        "mean_score":float(p.mean()),
        "observed_prevalence":float(y.mean()),
    }

def bins_table(y,p,bins=10):
    y=np.asarray(y,int); p=np.clip(np.asarray(p,float),0,1)
    idx=np.minimum((p*bins).astype(int),bins-1)
    rows=[]
    for k in range(bins):
        m=idx==k
        rows.append({
            "bin":k,"low":k/bins,"high":(k+1)/bins,"n":int(m.sum()),
            "score_mean":float(p[m].mean()) if m.any() else np.nan,
            "observed_rate":float(y[m].mean()) if m.any() else np.nan,
        })
    return rows

def load_predictions(path: Path, reference: Path|None=None):
    d=pd.read_csv(path)
    required={"target","seed","PUBCHEM_CID","parent_ik","gold","prediction"}
    missing=required-set(d.columns)
    if missing: raise ValueError(f"Missing columns: {sorted(missing)}")
    if len(d)!=19020: raise ValueError(f"Expected 19020 prediction rows, found {len(d)}")
    if set(d.target)!=set(TARGETS): raise ValueError("Unexpected target set")
    if d.duplicated(["target","seed","parent_ik"]).any(): raise ValueError("Duplicated target/seed/parent rows")
    if d.parent_ik.nunique()!=317 or d.seed.nunique()!=20: raise ValueError("Unexpected PAMPA parent or seed count")
    if not d.groupby(["target","seed"]).size().eq(317).all(): raise ValueError("Incomplete target/seed coverage")
    agg=d.groupby(["parent_ik","target"],sort=True).agg(
        gold=("gold","first"), score=("prediction","mean"), n_seed=("seed","nunique")).reset_index()
    w=agg.pivot(index="parent_ik",columns="target",values="score").sort_index()
    y=d.groupby("parent_ik").gold.first().reindex(w.index).to_numpy(int)
    if (len(y),int(y.sum()),int((y==0).sum()))!=(317,213,104): raise ValueError("Unexpected PAMPA class counts")
    raw={t:w[t].to_numpy(float) for t in TARGETS}
    if reference and reference.exists():
        ref=pd.read_csv(reference).set_index("target")
        for t in TARGETS:
            m=metrics(y,raw[t])
            for ref_col,metric_col in [("auroc","auroc"),("auprc","auprc"),("brier","brier"),("ece","ece10")]:
                if abs(m[metric_col]-float(ref.loc[t,ref_col]))>5e-6:
                    raise ValueError(f"Raw PAMPA anchor mismatch: {t} {ref_col}")
    return w.index.to_numpy(),y,raw

def crossfit(y,score,seeds=DEFAULT_SEEDS,n_splits=5):
    y=np.asarray(y,int); score=np.asarray(score,float)
    for repeat in seeds:
        fold_id=np.empty(len(y),int)
        calibrated=np.full(len(y),np.nan)
        coeff=[]
        cv=StratifiedKFold(n_splits=n_splits,shuffle=True,random_state=repeat)
        for fold,(train,test) in enumerate(cv.split(score.reshape(-1,1),y)):
            model=LogisticRegression(C=1e6,solver="lbfgs",max_iter=2000,random_state=repeat)
            model.fit(score[train].reshape(-1,1),y[train])
            calibrated[test]=model.predict_proba(score[test].reshape(-1,1))[:,1]
            fold_id[test]=fold
            coeff.append({
                "repeat_seed":repeat,"fold":fold,"train_n":len(train),"test_n":len(test),
                "slope":float(model.coef_[0,0]),"intercept":float(model.intercept_[0]),
                "train_prevalence":float(y[train].mean()),
            })
        if not np.isfinite(calibrated).all(): raise RuntimeError("Cross-fitted predictions contain non-finite values")
        yield repeat,fold_id,calibrated,coeff

def reliability_plot(y,raw,cal,target,path):
    fig,ax=plt.subplots(figsize=(5.2,4.4))
    ax.plot([0,1],[0,1],"--",color="0.55",lw=1,label="Ideal")
    for name,p,color in [("Raw score",raw,"#4F93D0"),("Cross-fitted Platt",cal,"#9B70C7")]:
        tab=pd.DataFrame(bins_table(y,p,bins=5))
        tab=tab[tab.n>0]
        ax.plot(tab.score_mean,tab.observed_rate,"o-",lw=1.3,ms=4,label=name,color=color)
    ax.set(xlim=(0,1),ylim=(0,1),xlabel="Mean score in bin",ylabel="Observed PAMPA-positive fraction",
           title=f"{TARGET_NAMES[target]} PAMPA reliability")
    ax.legend(frameon=False,fontsize=8)
    fig.tight_layout(); fig.savefig(path,dpi=240); plt.close(fig)

def main():
    root=Path(__file__).resolve().parents[2]
    ap=argparse.ArgumentParser()
    ap.add_argument("--input",type=Path,default=root/"results/stage4/pampa/pampa_predictions_by_seed.csv")
    ap.add_argument("--reference",type=Path,default=root/"results/stage4/pampa/pampa_mean_seed_metrics.csv")
    ap.add_argument("--out",type=Path,default=root/"results/stage6/pampa_calibration")
    ap.add_argument("--seeds",default="42,43,44")
    ap.add_argument("--folds",type=int,default=5)
    args=ap.parse_args()

    seeds=tuple(int(x) for x in args.seeds.split(","))
    out=args.out.resolve(); out.mkdir(parents=True,exist_ok=True)
    ids,y,raw=load_predictions(args.input.resolve(),args.reference.resolve())

    locked=[]; metrics_rows=[]; oof_rows=[]; coeff_rows=[]; bin_rows=[]
    seed42_cal={}
    for target in TARGETS:
        r=raw[target]
        locked.append({"target":target,"method":"raw_clipped",**metrics(y,r)})
        for repeat,fold,pcal,coeff in crossfit(y,r,seeds,n_splits=args.folds):
            metrics_rows.append({"target":target,"seed":repeat,"method":"raw_clipped",**metrics(y,r)})
            metrics_rows.append({"target":target,"seed":repeat,"method":"platt_oof",**metrics(y,pcal)})
            for c in coeff:
                coeff_rows.append({"target":target,**c})
            for parent,gold,raw_score,cal_score,fid in zip(ids,y,r,pcal,fold):
                oof_rows.append({
                    "target":target,"repeat_seed":repeat,"parent_ik":parent,"gold":int(gold),
                    "fold":int(fid),"raw_score":float(raw_score),"platt_oof":float(cal_score),
                })
            if repeat==seeds[0]:
                seed42_cal[target]=pcal.copy()
                for method,p in [("raw_clipped",r),("platt_oof",pcal)]:
                    for row in bins_table(y,p,bins=10):
                        bin_rows.append({"target":target,"repeat_seed":repeat,"method":method,**row})

    metrics_df=pd.DataFrame(metrics_rows)
    summary=[]
    for (target,method),g in metrics_df.groupby(["target","method"],sort=False):
        row={"target":target,"method":method}
        for col in ["auroc","auprc","brier","ece10","logloss","mean_score","observed_prevalence"]:
            row[col+"_mean"]=float(g[col].mean())
            row[col+"_sd"]=float(g[col].std(ddof=1))
        summary.append(row)
    summary_df=pd.DataFrame(summary)

    pd.DataFrame(locked).to_csv(out/"locked_external_metrics.csv",index=False)
    metrics_df.to_csv(out/"crossfit_metrics_by_repeat.csv",index=False)
    summary_df.to_csv(out/"crossfit_summary_mean_sd.csv",index=False)
    pd.DataFrame(oof_rows).to_csv(out/"crossfit_oof_predictions.csv",index=False)
    pd.DataFrame(coeff_rows).to_csv(out/"calibrator_coefficients.csv",index=False)
    pd.DataFrame(bin_rows).to_csv(out/"calibration_bins_seed42.csv",index=False)
    for t in TARGETS:
        reliability_plot(y,raw[t],seed42_cal[t],t,out/f"reliability_{TARGET_NAMES[t]}.png")
    manifest={
        "input":str(args.input.resolve()),"reference":str(args.reference.resolve()),
        "input_sha256":sha256(args.input.resolve()),"reference_sha256":sha256(args.reference.resolve()),
        "n_parents":317,"positive":213,"negative":104,"n_seed_predictions":20,
        "crossfit_repeats":list(seeds),"folds":args.folds,
        "sklearn":sklearn.__version__,"python":platform.python_version(),
    }
    (out/"run_manifest.json").write_text(json.dumps(manifest,indent=2,ensure_ascii=False),encoding="utf-8")

if __name__=="__main__":
    main()
